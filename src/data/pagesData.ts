export function getPageBySlug(slug: string): PageInfo | undefined {
  return PAGES_DATA.find((p) => p.slug === slug);
}

export function getPageByIndex(index: number): PageInfo | undefined {
  return PAGES_DATA[index];
}

export function getAdjacentPages(currentNum: number): { prev: PageInfo | null; next: PageInfo | null } {
  const prev = currentNum > 1 ? PAGES_DATA.find((p) => p.num === currentNum - 1) || null : null;
  const next = currentNum < 35 ? PAGES_DATA.find((p) => p.num === currentNum + 1) || null : null;
  return { prev, next };
}
